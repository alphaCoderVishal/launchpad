CREATE TABLE services (
  name VARCHAR(40) PRIMARY KEY,
  owner VARCHAR(80) NOT NULL,
  active_release VARCHAR(40),
  active_container VARCHAR(100),
  active_port INTEGER,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE deployments (
  id VARCHAR(36) PRIMARY KEY,
  service_name VARCHAR(40) NOT NULL REFERENCES services(name),
  release_name VARCHAR(40) NOT NULL,
  environment VARCHAR(10) NOT NULL,
  requested_by VARCHAR(80) NOT NULL,
  request_key VARCHAR(80) NOT NULL,
  status VARCHAR(30) NOT NULL,
  detail VARCHAR(500) NOT NULL,
  candidate_container VARCHAR(100) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(requested_by, request_key)
);
CREATE TABLE audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deployment_id VARCHAR(36) NOT NULL REFERENCES deployments(id),
  actor VARCHAR(80) NOT NULL,
  event_type VARCHAR(50) NOT NULL,
  detail VARCHAR(500) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX deployments_queue ON deployments(status, created_at);
CREATE INDEX audit_timeline ON audit_events(deployment_id, id);
